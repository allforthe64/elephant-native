import { useState, useEffect } from 'react'

import { StatusBar } from 'expo-status-bar';
import { StyleSheet, Text, View } from 'react-native';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { onAuthStateChanged } from 'firebase/auth'
import { firebaseAuth } from '../firebaseConfig';
import AppPressable from '../components/ui/AppPressable'
import ContentShell from '../components/ui/ContentShell'
import { TestIds } from '../constants/testIds'
import { useResponsiveLayout, tabletStyle } from '../hooks/useResponsiveLayout'

import {
  useFonts,
  Anybody_700Bold,
  Anybody_900Black,
} from '@expo-google-fonts/anybody'


export default function Home({navigation: {navigate}}) {
  const [loading, setLoading] = useState(true)
  const { isTablet, select } = useResponsiveLayout()

  const [fontsLoaded] = useFonts({
    Anybody_700Bold,
    Anybody_900Black
  })

  useEffect(() => {
    const unsubscribe = onAuthStateChanged(firebaseAuth, (user) => {
      if (user) navigate('Dashboard')
      else setLoading(false)
    })
    return unsubscribe
  }, [navigate])

  const insets = useSafeAreaInsets()

  if (!fontsLoaded) return null

  return (
    <>
      {loading ?
        <View style={{width: '100%', height: '100%', display: 'flex', justifyContent: 'center', alignItems: 'center', backgroundColor: '#593060'}}>
          <Text style={{
            color: 'white',
            fontWeight: '600',
            fontSize: 25
          }}>Loading...</Text>
        </View>
      :
        <View style={{
          flex: 1,
          backgroundColor: '#593060',
          alignItems: 'center',
          justifyContent: 'center',
          paddingTop: insets.top,
          paddingBottom: insets.bottom
        }}>
          <ContentShell variant="form" style={styles.shell}>
            <View style={tabletStyle(isTablet, styles.modal, tabletStyles.modal)}>
              <Text style={[{fontFamily: 'Anybody_900Black'}, tabletStyle(isTablet, styles.bigHeader, tabletStyles.bigHeader)]}>ORGANIZE</Text>
              <Text style={[{fontFamily: 'Anybody_700Bold'}, styles.subheading]}>with</Text>
              <Text style={[{fontFamily: 'Anybody_700Bold'}, tabletStyle(isTablet, styles.subheading1, tabletStyles.subheading1)]}>MyElephantApp</Text>
              <View style={styles.wrapperContainer}>
                <AppPressable
                  testID={TestIds.home.signIn}
                  accessibilityLabel="Sign In or Sign Up"
                  style={tabletStyle(isTablet, styles.button, tabletStyles.button)}
                  onPress={() => navigate('Sign In/Sign Up')}
                >
                    <Text style={[{fontFamily: 'Anybody_700Bold'}, styles.buttonText]}>Sign In/Sign Up</Text>
                </AppPressable>
                <AppPressable
                  testID={TestIds.home.about}
                  accessibilityLabel="I have a question"
                  style={tabletStyle(isTablet, styles.button, tabletStyles.button)}
                  onPress={() => navigate('About')}
                >
                    <Text style={[{fontFamily: 'Anybody_700Bold'}, styles.buttonText]}>I have a question</Text>
                </AppPressable>
              </View>
              <Text style={[{fontFamily: 'Anybody_700Bold'}, styles.subheading, { marginTop: select('10%', 32) }]}>Take control of your personal information</Text>
              <Text style={[{fontFamily: 'Anybody_700Bold'}, tabletStyle(isTablet, styles.tagline, tabletStyles.tagline)]}>*A portion of all proceeds generated by My Elephant App will be donated to saving endangered Elephants around the globe</Text>
            </View>
          </ContentShell>
          <StatusBar style="auto" />
        </View>
      }
    </>
  );
}

const styles = StyleSheet.create({
  shell: {
    width: '100%',
    alignItems: 'center',
    justifyContent: 'center',
  },
  modal: {
    width: '90%',
    height: '60%',
    paddingBottom: 10,
    position: 'absolute',
    display: 'flex',
    flexDirection: 'column',
    alignItems: 'center',
    alignSelf: 'center',
  },
  bigHeader: {
    color: 'white',
    fontSize: 60,
    textAlign: 'center',
    // Don't set fontWeight with a weight-specific fontFamily (Android renders blank glyphs)
    marginBottom: '6%'
  },
  subheading: {
    color: 'white',
    textAlign: 'center',
    fontSize: 22,
  },
  subheading1: {
    color: 'white',
    textAlign: 'center',
    fontSize: 35,
    marginBottom: '10%'
  },
  tagline: {
    color: 'white',
    textAlign: 'center',
    fontSize: 10,
    marginTop: '15%'
  },
  wrapperContainer: {
    display: 'flex',
    width: '100%',
    flexDirection: 'column',
    alignItems: 'center'
  },
  button: {
    width: '75%',
    borderRadius: 25,
    backgroundColor: '#FFE562',
    paddingTop: '2%',
    paddingBottom: '2%',
    marginBottom: '5%',
  },
  buttonText: {
    textAlign: 'center',
    fontSize: 22,
    color: '#593060'
  }
});

const tabletStyles = StyleSheet.create({
  modal: {
    width: '100%',
    height: undefined,
    maxWidth: 480,
    position: 'relative',
    paddingVertical: 24,
  },
  bigHeader: {
    fontSize: 72,
    marginBottom: 24,
  },
  subheading1: {
    fontSize: 40,
    marginBottom: 40,
  },
  button: {
    width: '100%',
    maxWidth: 360,
    paddingVertical: 14,
    marginBottom: 16,
  },
  tagline: {
    fontSize: 13,
    marginTop: 40,
    paddingHorizontal: 16,
    lineHeight: 18,
  },
})
